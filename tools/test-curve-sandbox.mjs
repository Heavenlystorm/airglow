import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { api, rigPage, root, until } from "./isolated-browser-rig.mjs";

const out = process.env.AIRGLOW_CURVE_OUTPUT || join(root, "output/curve-sandbox");
mkdirSync(out, {recursive:true});
const dutyField = i => `[data-row="${i}"] [data-sb-cell="1"]`;
const mutations = page => {
  const writes = [];
  page.on("request", r => { if (r.method() === "POST") writes.push(new URL(r.url()).pathname); });
  return writes;
};

test("compares and sweeps curves locally and saves an inactive curve only after explicit editor review", async t => {
  const page = await rigPage(t, "fans"), writes = mutations(page);
  const saved = (await api("/api/curves")).curves, base = (await api("/api/state")).fans.base_curve;
  await page.locator("#curve-sandbox").click();
  await page.locator("[data-sb-draft]").selectOption("silent");
  await page.locator("[data-sb-comparison]").selectOption("balanced");
  await page.locator(dutyField(0)).fill("33");
  await page.locator("[data-sb-previous]").fill("40");
  const slider = page.locator("#sb-temperature");
  await slider.focus(); await slider.press("Home");
  assert.equal(await page.locator("[data-sb-target]").innerText(), "33%");
  assert.equal(await page.locator("[data-sb-saved]").innerText(), "30%");
  assert.equal(await page.locator("[data-sb-command]").innerText(), "35%");
  await page.locator("[data-sb-mode]").selectOption("missing");
  assert.equal(await page.locator("[data-sb-command]").innerText(), "40%");
  assert.ok(await slider.isDisabled());
  await page.locator("[data-sb-mode]").selectOption("hot");
  assert.equal(await page.locator("[data-sb-command]").innerText(), "100%");
  await page.locator("[data-sb-mode]").selectOption("normal");
  await page.locator("[data-sb-play]").click();
  await until(() => slider.inputValue(), value => Number(value) > 20);
  await page.locator("[data-sb-play]").click();
  assert.equal(await page.locator("[data-sb-play]").innerText(), "Resume sweep");
  await slider.focus(); await slider.press("End");
  assert.equal(await page.locator("[data-sb-command]").innerText(), "100%");
  await slider.press("Home"); for (let i = 0; i < 40; i++) await slider.press("ArrowRight");
  await page.screenshot({ path: join(out, "curve-sandbox-desktop.png") });
  await page.locator("[data-sb-draft]").selectOption("performance");
  await page.locator("[data-sb-draft]").selectOption("silent");
  assert.equal(await page.locator(dutyField(0)).inputValue(), "33");
  await page.locator("[data-sb-review]").click();
  await until(() => page.locator("#curve-lede").textContent(), v => v.includes("Reviewing Silent"));
  assert.deepEqual(writes, []);
  assert.equal((await api("/api/state")).fans.base_curve, base);
  assert.deepEqual((await api("/api/curves")).curves.silent, saved.silent);
  const result = page.waitForResponse(r => r.url().endsWith("/api/curves/silent") && r.request().method() === "POST");
  await page.locator("#curve-save").click(); const response = await result;
  assert.equal(response.status(), 200);
  assert.deepEqual(response.request().postDataJSON().expected_points, saved.silent);
  assert.equal((await api("/api/curves")).curves.silent[0][1], 33);
  assert.equal((await api("/api/state")).fans.base_curve, base);
  assert.deepEqual(writes, ["/api/curves/silent"]);
});

test("preserves invalid drafts, handles Fahrenheit input and detects an externally revised curve", async t => {
  await api("/api/settings", { temp_unit: "F" });
  const page = await rigPage(t, "fans", 390, 844);
  await page.locator("#curve-sandbox").click();
  await page.locator("[data-sb-draft]").selectOption("performance");
  const first = page.getByRole("spinbutton", {name:"Point 1 temperature in °F"});
  assert.equal(await first.inputValue(), "104");
  await first.fill(""); assert.ok(await page.locator("[data-sb-review]").isDisabled());
  await page.locator("[data-sb-comparison]").selectOption("silent");
  await page.locator("[data-sb-draft]").selectOption("balanced");
  await page.locator("[data-sb-draft]").selectOption("performance");
  assert.equal(await first.inputValue(), "");
  await first.fill("102.2"); await page.locator(dutyField(0)).fill("44");
  await page.locator("[data-sb-add]").click();
  assert.ok(await page.locator("[data-row]").count() > 4);
  await page.locator("[data-row]:last-child [data-sb-remove]").click();
  await page.screenshot({ path: join(out, "curve-sandbox-mobile.png") });
  assert.ok(await page.locator("#sheet").evaluate(e => e.scrollWidth <= e.clientWidth + 1));
  await page.locator("[data-sb-review]").click();
  const existing = (await api("/api/curves")).curves.performance;
  const remote = existing.map(p => [...p]); remote[0][1] = 50;
  await api("/api/curves/performance", {points: remote});
  const stopped = page.waitForResponse(r => r.url().endsWith("/api/curves/performance") && r.request().method() === "POST");
  await page.locator("#curve-save").click();
  assert.equal((await stopped).status(), 409);
  assert.deepEqual((await api("/api/curves")).curves.performance, remote);
  await until(() => page.locator("#toast").textContent(), s => s.includes("updated dashed line"));
  assert.ok(await page.locator("#curve-save").isEnabled());
  const explicit = page.waitForResponse(r => r.url().endsWith("/api/curves/performance") && r.request().method() === "POST");
  await page.locator("#curve-save").click();
  assert.equal((await explicit).status(), 200);
  const latest = (await api("/api/curves")).curves.performance;
  assert.deepEqual(latest[0], [39, 44]);
  assert.equal((await api("/api/state")).fans.base_curve, "balanced");
});
